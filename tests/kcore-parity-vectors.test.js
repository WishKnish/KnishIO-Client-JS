import {
  afterEach,
  beforeAll,
  describe,
  expect,
  jest,
  test
} from '@jest/globals'
import fs from 'node:fs'
import path from 'node:path'
import * as kcore from '../src/libraries/kcore'
import Atom from '../src/Atom'
import Molecule from '../src/Molecule'
import Wallet from '../src/Wallet'
import CheckMolecule from '../src/libraries/CheckMolecule'

/**
 * kcore parity vectors (scripts/gen-kcore-parity-vectors.mjs in the KnishIOClientSDK monorepo):
 * 16 signed molecules (metadata, value transfer, token creation, wallet creation × OTS v1/v2 ×
 * unique/colliding createdAt) generated by the pure-JS path. Under whichever backend this run
 * uses, each must (a) verify — the molecular hash recomputed from its atoms and the OTS check — and
 * (b) re-sign from its secret to the same molecular hash and byte-identical otsFragments.
 *
 * Run once per backend: KNISHIO_KCORE=off npm test -- kcore-parity-vectors, then
 * KNISHIO_KCORE=require npm test -- kcore-parity-vectors. The fixture is vendored by
 * scripts/sync-cross-sdk-fixtures.sh; a missing fixture fails the suite.
 */
const VECTORS_PATH = path.resolve(__dirname, 'fixtures/kcore-parity-vectors.json')
const CASES = JSON.parse(fs.readFileSync(VECTORS_PATH, 'utf8')).vectors.molecules.tests
const EXPECTED_CASES = 16
const mode = (process.env.KNISHIO_KCORE ?? 'auto').toLowerCase()

// The binding src/libraries/kcore.js loaded, obtained through the same loader it uses
// (process.getBuiltinModule, not jest's `node:module`), so both share one module cache and a spy
// on it counts the native calls the SDK actually made.
function nativeKcore () {
  const specifier = process.env.KNISHIO_KCORE_MODULE || '@wishknish/knishio-kcore'
  const { createRequire } = process.getBuiltinModule('node:module')
  return createRequire(path.resolve(__dirname, '../src/libraries/kcore.js'))(specifier)
}

/**
 * Runs `fn`; in require mode also asserts that kcore computed every WOTS+ chain and address it
 * was handed (each native call returned, none threw into the pure-JS fallback).
 */
function onBackend (fn) {
  if (mode !== 'require') {
    fn()
    return
  }
  const lib = nativeKcore()
  const spies = ['chainsHex', 'wotsAddress', 'wotsAddressV2']
    .filter(name => typeof lib[name] === 'function')
    .map(name => [name, jest.spyOn(lib, name)])
  fn()
  const chains = spies.find(([name]) => name === 'chainsHex')[1]
  expect(chains.mock.calls.length).toBeGreaterThan(0)
  for (const [name, spy] of spies) {
    for (const call of spy.mock.results) {
      expect({ name, type: call.type, string: typeof call.value === 'string' }).toEqual({ name, type: 'return', string: true })
    }
  }
}

afterEach(() => {
  jest.restoreAllMocks()
})

describe('kcore parity vectors', () => {
  beforeAll(() => {
    kcore._reset()
  })

  test(`the fixture holds all ${EXPECTED_CASES} cases`, () => {
    expect(CASES).toHaveLength(EXPECTED_CASES)
    expect(new Set(CASES.map(vector => vector.name)).size).toBe(EXPECTED_CASES)
  })

  test(`backend matches KNISHIO_KCORE=${mode}`, () => {
    if (mode === 'require') {
      expect(kcore.available()).toBe(true)
      expect(['napi', 'wasm']).toContain(kcore.backend())
    } else if (mode === 'off') {
      expect(kcore.available()).toBe(false)
      expect(kcore.backend()).toBeNull()
    }
  })

  test.each(CASES)('$name verifies', (vector) => {
    const molecule = Molecule.fromJSON(vector.molecule)
    expect(molecule.molecularHash).toBe(vector.expected.molecularHash)
    onBackend(() => {
      expect(Atom.hashAtoms({ atoms: molecule.atoms })).toBe(vector.expected.molecularHash)
      expect(new CheckMolecule(molecule).ots()).toBe(true)
    })
  })

  test.each(CASES)('$name re-signs to the same molecular hash and otsFragments', (vector) => {
    const { secret, sourceToken, sourcePosition, otsVersion } = vector
    const molecule = Molecule.fromJSON(vector.molecule)
    expect(molecule.atoms.map(atom => atom.createdAt)).toEqual(vector.molecule.atoms.map(atom => atom.createdAt))
    for (const atom of molecule.atoms) {
      atom.otsFragment = null
    }
    onBackend(() => {
      molecule.secret = secret
      molecule.sourceWallet = new Wallet({ secret, token: sourceToken, position: sourcePosition, otsVersion })
      molecule.sign()
    })
    expect(molecule.molecularHash).toBe(vector.expected.molecularHash)
    expect(molecule.atoms.map(atom => atom.otsFragment)).toEqual(vector.expected.otsFragments)
  })
})
